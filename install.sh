#!/usr/bin/env bash
# =============================================================================
# FarsiGo — deploy the static website to an Nginx server on port 8080
#
# Usage:
#   ./install.sh              # deploy (nginx must already be installed)
#   ./install.sh --install    # install nginx first (Debian/Ubuntu, apt)
#   PORT=8080 SERVER_NAME=example.com ./install.sh
#   APP_DIR=/path/to/app DEPLOY_DIR=/var/www/farsigo ./install.sh
#
# What it does:
#   1. (optional) installs Nginx with apt
#   2. copies the app files to $DEPLOY_DIR (default: /var/www/farsigo)
#   3. writes an Nginx server block listening on $PORT (default: 8080)
#      (Debian/Ubuntu: /etc/nginx/sites-available + sites-enabled symlink;
#       other layouts:  /etc/nginx/conf.d/)
#   4. tests the config (nginx -t) and reloads/restarts Nginx
#   5. opens the firewall port if ufw is active (best effort)
#   6. health-checks http://127.0.0.1:$PORT/ and prints the URL
#
# Safe to re-run: files and config are overwritten, a timestamped backup of a
# previous FarsiGo Nginx config is kept next to the original.
# =============================================================================
set -euo pipefail

PORT="${PORT:-8080}"
SERVER_NAME="${SERVER_NAME:-_}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP_DIR="${APP_DIR:-$SCRIPT_DIR}"
DEPLOY_DIR="${DEPLOY_DIR:-/var/www/farsigo}"
SITE_NAME="farsigo"
INSTALL=0
[ "${1:-}" = "--install" ] && INSTALL=1

log()  { printf '\033[1;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m!!\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31mERROR:\033[0m %s\n' "$*" >&2; exit 1; }

# --- privileges -------------------------------------------------------------
if [ "$(id -u)" -eq 0 ]; then SUDO=""; else
  command -v sudo >/dev/null 2>&1 || die "Run as root or install sudo."
  SUDO="sudo"
fi

# --- 1. nginx ---------------------------------------------------------------
if ! command -v nginx >/dev/null 2>&1; then
  if [ "$INSTALL" -eq 1 ]; then
    log "Installing Nginx…"
    $SUDO apt-get update -y
    $SUDO DEBIAN_FRONTEND=noninteractive apt-get install -y nginx curl
  else
    die "Nginx is not installed. Re-run with:  $0 --install   (or install nginx manually)"
  fi
fi
log "Using $(nginx -v 2>&1)"

[ -f "$APP_DIR/index.html" ] || die "index.html not found in APP_DIR=$APP_DIR"

# --- 2. copy website files ----------------------------------------------------
log "Copying site files: $APP_DIR -> $DEPLOY_DIR"
$SUDO mkdir -p "$DEPLOY_DIR"
if command -v rsync >/dev/null 2>&1; then
  $SUDO rsync -a --delete \
    --include='index.html' --include='style.css' --include='app.js' \
    --include='data.js' --include='sentences.js' --include='verbs.js' \
    --include='readme.md' \
    --include='audio/' --include='audio/**' \
    --exclude='*' \
    "$APP_DIR/" "$DEPLOY_DIR/"
else
  for f in index.html style.css app.js data.js sentences.js verbs.js readme.md; do
    [ -f "$APP_DIR/$f" ] && $SUDO cp -a "$APP_DIR/$f" "$DEPLOY_DIR/$f"
  done
  # the bundled Persian audio pack (thousands of small MP3s)
  [ -d "$APP_DIR/audio" ] && $SUDO cp -a "$APP_DIR/audio" "$DEPLOY_DIR/audio"
fi
$SUDO chown -R www-data:www-data "$DEPLOY_DIR" 2>/dev/null || \
  $SUDO chown -R nginx:nginx "$DEPLOY_DIR" 2>/dev/null || \
  warn "Could not chown $DEPLOY_DIR to the nginx user (continuing)."
$SUDO find "$DEPLOY_DIR" -type d -exec chmod 755 {} +
$SUDO find "$DEPLOY_DIR" -type f -exec chmod 644 {} +

# --- 3. nginx server block ----------------------------------------------------
TMP_CONF="$(mktemp)"
cat > "$TMP_CONF" <<EOF
# FarsiGo — generated by install.sh
server {
    listen      $PORT;
    listen      [::]:$PORT;
    server_name $SERVER_NAME;

    root  $DEPLOY_DIR;
    index index.html;

    charset utf-8;

    # This is a static single-page-style app: fall back to index.html
    location / {
        try_files \$uri \$uri/ /index.html;
    }

    # Long-cache the static assets, but never cache the HTML entry point
    location ~* \.(?:css|js)$ {
        expires 7d;
        add_header Cache-Control "public, max-age=604800";
        access_log off;
    }
    # Bundled Persian audio: content-hashed file names, safe to cache for long
    location ~* \.mp3$ {
        expires 30d;
        add_header Cache-Control "public, max-age=2592000, immutable";
        access_log off;
    }
    location = /index.html {
        add_header Cache-Control "no-cache";
    }

    gzip on;
    gzip_types text/css application/javascript text/html;
    gzip_min_length 1024;

    add_header X-Content-Type-Options "nosniff" always;
    add_header X-Frame-Options "SAMEORIGIN" always;
    add_header Referrer-Policy "no-referrer-when-downgrade" always;

    access_log /var/log/nginx/${SITE_NAME}.access.log;
    error_log  /var/log/nginx/${SITE_NAME}.error.log;
}
EOF

if [ -d /etc/nginx/sites-available ]; then
  CONF_DEST="/etc/nginx/sites-available/$SITE_NAME"
  LINK_DEST="/etc/nginx/sites-enabled/$SITE_NAME"
  [ -f "$CONF_DEST" ] && $SUDO cp -a "$CONF_DEST" "$CONF_DEST.bak.$(date +%Y%m%d%H%M%S)"
  $SUDO install -m 644 "$TMP_CONF" "$CONF_DEST"
  $SUDO ln -sf "$CONF_DEST" "$LINK_DEST"
  # A default site listening on 8080 would clash — warn, don't touch it.
  if grep -Rqs "listen[[:space:]]\+8080" /etc/nginx/sites-enabled/default 2>/dev/null && [ "$PORT" = "8080" ]; then
    warn "/etc/nginx/sites-enabled/default also mentions port 8080 — check for conflicts."
  fi
else
  CONF_DEST="/etc/nginx/conf.d/$SITE_NAME.conf"
  [ -f "$CONF_DEST" ] && $SUDO cp -a "$CONF_DEST" "$CONF_DEST.bak.$(date +%Y%m%d%H%M%S)"
  $SUDO install -m 644 "$TMP_CONF" "$CONF_DEST"
fi
rm -f "$TMP_CONF"
log "Nginx config written to $CONF_DEST (port $PORT, root $DEPLOY_DIR)"

# --- 4. test + (re)start -------------------------------------------------------
log "Testing Nginx configuration…"
$SUDO nginx -t
if $SUDO systemctl is-active --quiet nginx 2>/dev/null; then
  log "Reloading Nginx…"
  $SUDO systemctl reload nginx
else
  log "Starting Nginx…"
  $SUDO systemctl enable --now nginx 2>/dev/null || $SUDO service nginx restart || $SUDO nginx
fi

# --- 5. firewall (best effort) ---------------------------------------------------
if command -v ufw >/dev/null 2>&1 && $SUDO ufw status 2>/dev/null | grep -q "Status: active"; then
  log "Allowing port $PORT through ufw…"
  $SUDO ufw allow "$PORT/tcp" >/dev/null || warn "ufw allow failed (continuing)."
fi

# --- 6. health check -------------------------------------------------------------
log "Health check on http://127.0.0.1:$PORT/ …"
for i in 1 2 3 4 5; do
  if curl -fsS -o /dev/null "http://127.0.0.1:$PORT/"; then
    echo
    log "✅ FarsiGo is live!"
    echo "   Local:   http://127.0.0.1:$PORT/"
    echo "   Network: http://<this-server-ip>:$PORT/   (server_name: $SERVER_NAME)"
    echo "   Files:   $DEPLOY_DIR"
    echo "   Logs:    /var/log/nginx/${SITE_NAME}.error.log"
    exit 0
  fi
  sleep 1
done
die "Nginx is running but http://127.0.0.1:$PORT/ did not respond. Check: sudo tail -n 50 /var/log/nginx/${SITE_NAME}.error.log"
